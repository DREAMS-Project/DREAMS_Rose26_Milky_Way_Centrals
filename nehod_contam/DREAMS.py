def sph2cart(r, t, p):
    x = r*np.cos(t)*np.sin(p)
    y = r*np.sin(t)*np.sin(p)
    z = r*np.cos(p)
    return x,y,z

def pol2cart(r, t, z):
    x = r*np.cos(t)
    y = r*np.sin(t)
    z = z
    return x,y,z

def cart2pol(x, y, z):
    r = np.sqrt(np.square(x) + np.square(y))
    t = np.arctan2(y, x)
    return r, t, z

def cart2sph(x, y, z):
    r = np.sqrt(x**2 + y**2 + z**2)
    phi = np.arccos(z / r)  
    theta = np.arctan2(y, x)
    theta = np.mod(theta, 2 * np.pi)
    return r, theta, phi

