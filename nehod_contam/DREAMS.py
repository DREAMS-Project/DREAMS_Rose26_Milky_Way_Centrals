    bulge_mass_neg = np.sum(masses_stars_wind[more_bound_indices[bulge_neg_cut_local]])
    
    pos_candidates_cut_local = (eta[more_bound_indices] >= 0)
    pos_candidates_indices_local = np.where(pos_candidates_cut_local)[0]
    
    if len(pos_candidates_indices_local) > 0:
        eta_pos_candidates = eta[more_bound_indices[pos_candidates_indices_local]]
        mass_pos_candidates = masses_stars_wind[more_bound_indices[pos_candidates_indices_local]]
        
        idx_sort_eta = np.argsort(eta_pos_candidates)
        cum_mass_pos = np.cumsum(mass_pos_candidates[idx_sort_eta])
        idx_mass_match = np.searchsorted(cum_mass_pos, bulge_mass_neg)
        
        indices_pos_to_add_local = pos_candidates_indices_local[idx_sort_eta[:idx_mass_match+1]]
    else:
        indices_pos_to_add_local = np.array([], dtype=int)

    indices_neg_to_add_local = np.where(bulge_neg_cut_local)[0]
    
    bulge_indices_local = np.concatenate([indices_neg_to_add_local, indices_pos_to_add_local])
    bulge_indices = more_bound_indices[bulge_indices_local]

    # 1.b. Find Pseudo-Bulge & Thin-Disk (from remaining *bound* particles)
    remaining_bound_indices_local = np.setdiff1d(np.arange(len(more_bound_indices)), bulge_indices_local)
    remaining_bound_indices = more_bound_indices[remaining_bound_indices_local]
    
    if len(remaining_bound_indices) > 0:
        eta_remaining_bound = eta[remaining_bound_indices]
        
        # Pseudo-bulge is 0 < eta <= ETA_THIN_DISK_CUT
        pseudo_bulge_cut_local = (eta_remaining_bound > 0) & (eta_remaining_bound <= ETA_THIN_DISK_CUT)
        pseudo_bulge_indices = remaining_bound_indices[pseudo_bulge_cut_local]

        # Thin-disk (bound part) is eta > ETA_THIN_DISK_CUT
        thin_disk_cut_local = (eta_remaining_bound > ETA_THIN_DISK_CUT)
        thin_disk_indices = remaining_bound_indices[thin_disk_cut_local]

    # --- B: Less Bound Particles (E > Ecut_to_use) ---
    less_bound_cut = (E_particles > Ecut_to_use)
    less_bound_indices = all_indices[less_bound_cut]

    if len(less_bound_indices) > 0:
        # 2.a. Find Halo (symmetric component)
        halo_neg_cut_local = (eta[less_bound_indices] < 0)
        halo_mass_neg = np.sum(masses_stars_wind[less_bound_indices[halo_neg_cut_local]])

        pos_candidates_cut_local_halo = (eta[less_bound_indices] >= 0)
        pos_candidates_indices_local_halo = np.where(pos_candidates_cut_local_halo)[0]
        
        if len(pos_candidates_indices_local_halo) > 0:
            eta_pos_candidates_halo = eta[less_bound_indices[pos_candidates_indices_local_halo]]
            mass_pos_candidates_halo = masses_stars_wind[less_bound_indices[pos_candidates_indices_local_halo]]
            
            idx_sort_eta_halo = np.argsort(eta_pos_candidates_halo)
            cum_mass_pos_halo = np.cumsum(mass_pos_candidates_halo[idx_sort_eta_halo])
            idx_mass_match_halo = np.searchsorted(cum_mass_pos_halo, halo_mass_neg)

            indices_pos_to_add_local_halo = pos_candidates_indices_local_halo[idx_sort_eta_halo[:idx_mass_match_halo+1]]
        else:
            indices_pos_to_add_local_halo = np.array([], dtype=int)

        indices_neg_to_add_local_halo = np.where(halo_neg_cut_local)[0]

        halo_indices_local = np.concatenate([indices_neg_to_add_local_halo, indices_pos_to_add_local_halo])
        halo_indices = less_bound_indices[halo_indices_local]

        # 2.b. Find Thick-Disk (from remaining *less-bound* particles)
        remaining_unbound_indices_local = np.setdiff1d(np.arange(len(less_bound_indices)), halo_indices_local)
        thick_disk_indices = less_bound_indices[remaining_unbound_indices_local]

    return bulge_indices, pseudo_bulge_indices, thin_disk_indices, thick_disk_indices, halo_indices

