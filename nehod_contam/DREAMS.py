    prominences = properties['prominences']
    
    # Sort the peaks by how prominent they are (most prominent first)
    idx_sorted_by_prominence = np.argsort(prominences)[::-1]
    
    # Get the indices of the two most prominent peaks
    peak1_idx = peaks_idx[idx_sorted_by_prominence[0]]
    peak2_idx = peaks_idx[idx_sorted_by_prominence[1]]
    
    # Find the minimum *between* these two, regardless of their order
    start_idx = min(peak1_idx, peak2_idx)
    end_idx = max(peak1_idx, peak2_idx)
    
    # The minimum index in this slice
    # Add a small check in case peaks are adjacent
    if start_idx == end_idx - 1:
        min_slice_idx = 0 # No room between them, just take the start
    else:
        min_slice_idx = np.argmin(counts_weighted[start_idx:end_idx])
    
    # The index in the *full* histogram
    min_global_idx = start_idx + min_slice_idx
    
