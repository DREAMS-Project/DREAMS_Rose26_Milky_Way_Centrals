def select_halo_stars(pcat, tree_cat, mw_idx):

    fof_list = get_fof_tree(tree_cat, mw_idx)
    halo_times, halo_coords = track_halo_center(tree_cat, fof_list)

    ftime = pcat['PartType4/GFM_StellarFormationTime']
    bpos = pcat['PartType4/BirthPos']

    wind_cut = ftime > 0
    ftime = ftime[wind_cut]
    bpos = bpos[wind_cut]

    xspl = CubicSpline(halo_times, halo_coords[:,0])
    yspl = CubicSpline(halo_times, halo_coords[:,1])
    zspl = CubicSpline(halo_times, halo_coords[:,2])
    halo_xpos = xspl(ftime)
    halo_ypos = yspl(ftime)
    halo_zpos = zspl(ftime)
    halo_pos = np.array([halo_xpos, halo_ypos, halo_zpos]).T

    halo_dist = np.sqrt(np.sum(np.square(halo_pos - bpos), axis=1)) / h
    halo_cut = halo_dist > 50

    return halo_cut

